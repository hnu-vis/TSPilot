function initialLocale(): UiLocale {
  if (typeof window === 'undefined') return 'en';
  let stored: string | null = null;
  try {
    stored = localStorage.getItem(STORAGE_KEY);
  } catch {
    // Storage can be unavailable in privacy-restricted browsing contexts.
  }
  if (stored === 'zh-CN' || stored === 'en') return stored;
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

function interpolate(template: string, variables?: Variables) {
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(variables[key] ?? `{${key}}`));
}

export function translateUi(locale: UiLocale, key: string, variables?: Variables) {
  return interpolate(locale === 'zh-CN' ? zhCN[key] || key : key, variables);
}

type I18nValue = {
  locale: UiLocale;
  setLocale: (locale: UiLocale) => void;
  t: (key: string, variables?: Variables) => string;
  formatDate: (value: Date, options?: Intl.DateTimeFormatOptions) => string;
};

const defaultValue: I18nValue = {
  locale: 'en',
  setLocale: () => undefined,
  t: (key, variables) => interpolate(key, variables),
  formatDate: (value, options) => value.toLocaleDateString('en', options),
};

const I18nContext = createContext<I18nValue>(defaultValue);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<UiLocale>(initialLocale);

  useEffect(() => {
    if (typeof document === 'undefined') return;
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch (error) {
      console.warn('Unable to save interface language.', error);
    }
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, variables) => translateUi(locale, key, variables),
    formatDate: (value, options) => value.toLocaleDateString(locale, options),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
